#!/usr/bin/env python3
"""Generate baseline.egg / touch.egg: the same computation with and without a
cell-published contact point.

The shape mirrors eggcc's real extraction-cost machinery:

  (constructor CP (Tm i64) TC)          -- like TCPair: the OUTPUT column is
                                           unique, one TC value per row
  (constructor Smaller (TC TC) TC)         -- like Smaller: a pending comparison
                                           whose two fields are TC *values*

To read the two costs the rule must therefore resolve `Smaller`'s fields back to
the `CP` rows that produced them -- a lookup in the *reverse* direction (probe
the output column), which the LHS atoms cannot express as a forward key.

baseline.egg does exactly that. touch.egg keeps the same LHS and adds
`Costs(l, t1, c1, t2, c2)`, a contact point the cell publishes with the
correlation already resolved, so the two `CP` atoms become forward key lookups
and the `Smaller` atom becomes a point check. Atom count goes UP by one.

Usage: make_data.py OUTDIR [K] [M]
"""
import pathlib
import random
import sys

out = pathlib.Path(sys.argv[1])
K = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
M = int(sys.argv[3]) if len(sys.argv) > 3 else 2000
out.mkdir(parents=True, exist_ok=True)
random.seed(7)

# deterministic data: K cost pairs, M pending comparisons over them
cps = [(f"(Leaf {i})", random.randint(1, 50)) for i in range(K)]
pairs = [(random.randrange(K), random.randrange(K)) for _ in range(M)]

HEADER = """;; generated by make_data.py -- same data in both files
(sort Tm)
(sort TC)
(constructor Leaf (i64) Tm)
(constructor CP (Tm i64) TC)
(constructor Smaller (TC TC) TC)
(relation Win (TC i64 i64))
"""


def data():
    lines = []
    for i, (t, c) in enumerate(cps):
        lines.append(f"(let cp{i} (CP {t} {c}))")
    for j, (a, b) in enumerate(pairs):
        # a `let` creates the row and names its output, exactly like the real
        # ExtractedExpr merge producing a fresh Smaller node
        lines.append(f"(let sm{j} (Smaller cp{a} cp{b}))")
    return "\n".join(lines)


BASELINE_RULE = """
;; baseline: no contact point. The planner must resolve Smaller's two TC fields
;; back to their CP rows (probe the value column) to reach the costs.
(ruleset run)
(rule ((= l (Smaller (CP t1 c1) (CP t2 c2)))
       (<= c1 c2))
      ((Win l c1 c2)) :ruleset run)
(run run 1)
(print-function Win {n})
""".format(n=M + 10)

TOUCH_RULE = """
;; the cell publishes the correlation it already proved: which CP rows produced
;; which Smaller fields, with the costs inline.
{build}
;; touch: the original LHS is kept; one contact point is added. Atom count is
;; higher, but Costs is narrower than every atom the baseline had to enumerate.
(ruleset run)
(rule ((Costs l t1 c1 t2 c2)
       (= l (Smaller (CP t1 c1) (CP t2 c2)))
       (<= c1 c2))
      ((Win l c1 c2)) :ruleset run)
(run run 1)
(print-function Win {n})
"""


def costs_facts():
    lines = ["(relation Costs (TC Tm i64 Tm i64))"]
    for j, (a, b) in enumerate(pairs):
        lines.append(f"(Costs sm{j} {cps[a][0]} {cps[a][1]} {cps[b][0]} {cps[b][1]})")
    return "\n".join(lines)


INLINE_HEADER = """;; generated by make_data.py -- same comparison computed with the
;; representation a cost-aware merge would enable: the two (term, cost) pairs are
;; inline columns of the comparison node, so there is nothing to resolve.
(sort Tm)
(sort TC)
(constructor Leaf (i64) Tm)
(constructor CP (Tm i64) TC)
(constructor SmallerI (Tm i64 Tm i64) TC)
(relation Win (TC i64 i64))
"""
INLINE_RULE = """
(ruleset run)
(rule ((= l (SmallerI t1 c1 t2 c2)) (<= c1 c2))
      ((Win l c1 c2)) :ruleset run)
(run run 1)
(print-function Win {n})
"""


def inline_data():
    lines = []
    for j, (a, b) in enumerate(pairs):
        lines.append(
            f"(let sm{j} (SmallerI {cps[a][0]} {cps[a][1]} {cps[b][0]} {cps[b][1]}))")
    return "\n".join(lines)


(out / 'baseline.egg').write_text(HEADER + data() + "\n" + BASELINE_RULE)
(out / 'inline.egg').write_text(INLINE_HEADER + inline_data() + "\n" + INLINE_RULE.format(n=M + 10))
TOUCH_DROP_RULE = """
;; phase 2: once the cell guarantees the correlation, the checks it guarantees
;; can be DELETED rather than kept alongside the contact point.
(ruleset run)
(rule ((Costs l t1 c1 t2 c2) (<= c1 c2))
      ((Win l c1 c2)) :ruleset run)
(run run 1)
(print-function Win {n})
"""

(out / 'touch.egg').write_text(
    HEADER + data() + "\n" + TOUCH_RULE.format(build=costs_facts(), n=M + 10))
(out / 'touch_drop.egg').write_text(
    HEADER + data() + "\n" + costs_facts() + "\n" + TOUCH_DROP_RULE.format(n=M + 10))
print(f"wrote {out}/baseline.egg, touch.egg, touch_drop.egg, inline.egg  (K={K} CP rows, M={M} comparisons)")
