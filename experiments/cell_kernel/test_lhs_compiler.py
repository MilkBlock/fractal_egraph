#!/usr/bin/env python3
"""Source-compiler checks against JSON exported by the native egglog parser.

These checks cover the conjunct partition and exact reconstruction, not runtime
matching, mutations, or performance. The fixture is generated by lhs_ast.rs;
this file does not parse egglog text or manufacture a substitute CICM rule.
"""
import argparse
from copy import deepcopy
import json
from pathlib import Path
import unittest

from lhs_compiler import body_text, compile_rule, expressions, variables, walk

ROOT = Path(__file__).resolve().parents[2]
AST_PATH = ROOT / "out/lhs-touchpoints/ast.json"


def transform(value, variable_map):
    if isinstance(value, list):
        return [transform(item, variable_map) for item in value]
    if not isinstance(value, dict):
        return value
    if value.get("kind") == "var" and value["name"] in variable_map:
        return deepcopy(variable_map[value["name"]])
    return {key: transform(item, variable_map) for key, item in value.items()}


class NativeLhsCompilerTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not AST_PATH.is_file():
            raise FileNotFoundError(
                f"native parser fixture missing: {AST_PATH}; supply --ast PATH")
        report = json.loads(AST_PATH.read_text())
        if report.get("format") != "egglog-lhs-ast/v1" or not report.get("parse_only"):
            raise ValueError("fixture must come from the native lhs_ast exporter")
        cls.original = next(rule for rule in report["rules"] if rule["ruleset"] == "cicm")
        cls.signatures = report["signatures"]

    def setUp(self):
        self.rule = deepcopy(self.original)
        self.plan = compile_rule(self.rule, self.signatures)

    def assert_partition_and_reconstruction(self, plan, body):
        covered = list(plan.metadata["residual_indices"])
        for instance in plan.instances:
            indices = instance["source_indices"]
            covered.extend(indices)
            template = plan.templates[instance["template"]]
            actual = dict(zip((slot["name"] for slot in template["slots"]),
                              instance["arguments"]))
            rebuilt = transform(template["body"], actual)
            self.assertEqual(rebuilt, [body[index] for index in indices])
        self.assertEqual(sorted(covered), list(range(len(body))))
        self.assertEqual(len(set(covered)), len(covered))

    def test_actual_rule_partition_and_exact_reconstruction(self):
        self.assertEqual(len(self.rule["body"]), 18)
        self.assertEqual(self.plan.metadata["root_families"], {"Uop": ["e1", "e2"]})
        self.assertEqual(self.plan.metadata["owned_conjuncts"], 12)
        self.assertEqual(len(self.plan.instances), 2)
        self.assertEqual(len(self.plan.templates), 1)
        self.assertEqual([len(i["source_indices"]) for i in self.plan.instances], [6, 6])
        self.assert_partition_and_reconstruction(self.plan, self.rule["body"])

    def test_renderer_agrees_with_native_printed_body(self):
        self.assertEqual(" ".join(body_text(self.rule["body"]).split()),
                         " ".join(self.rule["body_text"].split()))

    def test_alpha_renaming_preserves_template(self):
        mapping = {name: {"kind": "var", "name": f"renamed_{index}"}
                   for index, name in enumerate(self.plan.metadata["named_variables"])}
        renamed = deepcopy(self.rule)
        renamed["body"] = transform(renamed["body"], mapping)
        other = compile_rule(renamed, self.signatures)
        self.assertEqual(other.templates, self.plan.templates)
        self.assert_partition_and_reconstruction(other, renamed["body"])

    def test_all_named_variables_and_distinct_outputs_survive(self):
        expected = "if_e pred orig_ins thn els tylist outer_ctx e1 o x ty t1 c1 e2 y t2 c2 orig_ins_len".split()
        self.assertEqual(self.plan.metadata["named_variables"], expected)
        self.assertEqual(len(self.plan.metadata["variable_sorts"]), 18)
        observed = set()
        for index in self.plan.metadata["residual_indices"]:
            observed.update(variables(self.rule["body"][index]))
        for instance in self.plan.instances:
            named = {arg["name"] for arg in instance["arguments"] if arg["kind"] == "var"}
            expected_fragment = set().union(*(variables(self.rule["body"][i])
                                              for i in instance["source_indices"]))
            self.assertEqual(named, expected_fragment)
            observed.update(named)
            branch = {"e1": {"x", "t1", "c1"}, "e2": {"y", "t2", "c2"}}
            self.assertTrue(branch[instance["root"]].issubset(named))
        self.assertEqual(observed, set(expected))

    def test_boolean_context_slot_and_literal_guard(self):
        template = self.plan.templates[0]
        literals = [node for fact in template["body"] for expr in expressions(fact)
                    for node in walk(expr) if node["kind"] == "literal"]
        self.assertEqual([(node["sort"], node["value"]) for node in literals], [("i64", 10)])
        bool_positions = [i for i, slot in enumerate(template["slots"]) if slot["sort"] == "bool"]
        self.assertEqual(len(bool_positions), 1)
        position = bool_positions[0]
        self.assertEqual([instance["arguments"][position]["value"]
                          for instance in self.plan.instances], [True, False])
        emitted = self.plan.emit("LiteralCheck")
        self.assertIn("(> 10 (Expr-size", emitted["producer_rules"])
        self.assertIn(" true ", emitted["rewritten_body"])
        self.assertIn(" false ", emitted["rewritten_body"])

    def test_cross_root_guard_and_term_equality_stay_residual(self):
        guard = {"kind": "fact", "expr": {"kind": "call", "head": "!=", "args": [
            {"kind": "var", "name": "e1"}, {"kind": "var", "name": "e2"}]}}
        self.rule["body"].append(guard)
        plan = compile_rule(self.rule, self.signatures)
        self.assertIn(18, plan.metadata["residual_indices"])
        rewritten = plan.emit("ResidualCheck")["rewritten_body"]
        self.assertIn("(!= e1 e2)", rewritten)
        self.assertIn("(= t1 t2)", rewritten)
        self.assert_partition_and_reconstruction(plan, self.rule["body"])

    def test_single_constructor_instance_falls_back_to_original_body(self):
        indices = self.plan.instances[0]["source_indices"]
        self.rule["body"] = [self.rule["body"][index] for index in indices]
        plan = compile_rule(self.rule, self.signatures)
        emitted = plan.emit("SingleCheck")
        self.assertEqual(plan.templates, [])
        self.assertEqual(plan.instances, [])
        self.assertEqual(emitted["producer_rules"], "")
        self.assertEqual(emitted["rewritten_body"], body_text(self.rule["body"]))
        self.assert_partition_and_reconstruction(plan, self.rule["body"])

    def test_changed_conjunct_order_is_safe_without_claiming_canonical_reordering(self):
        # This implementation shares source-ordered templates; it deliberately
        # does not claim invariance under arbitrary conjunction permutations.
        left, right = self.plan.instances[1]["source_indices"][:2]
        self.rule["body"][left], self.rule["body"][right] = self.rule["body"][right], self.rule["body"][left]
        plan = compile_rule(self.rule, self.signatures)
        self.assertEqual(len(plan.templates), 2)
        self.assert_partition_and_reconstruction(plan, self.rule["body"])

    def test_unknown_or_ambiguous_calls_reject(self):
        for candidate in (None, [self.signatures["Uop"], self.signatures["Uop"]]):
            signatures = deepcopy(self.signatures)
            signatures["Uop"] = candidate
            with self.subTest(signature=candidate), self.assertRaisesRegex(ValueError, "unknown or ambiguous"):
                compile_rule(self.rule, signatures)

    def test_inconsistent_or_unknown_literal_sort_rejects(self):
        for sort in ("Unknown", "bool"):
            rule = deepcopy(self.rule)
            literal = next(node for fact in rule["body"] for expr in expressions(fact)
                           for node in walk(expr) if node["kind"] == "literal" and node["sort"] == "i64")
            literal["sort"] = sort
            with self.subTest(sort=sort), self.assertRaisesRegex(ValueError, "literal sort"):
                compile_rule(rule, self.signatures)

    def test_conflicting_or_unresolved_variable_sorts_reject(self):
        signatures = deepcopy(self.signatures)
        signatures["Expr-size"]["output"] = "bool"
        with self.assertRaisesRegex(ValueError, "conflicting sorts"):
            compile_rule(self.rule, signatures)
        unknown = {"body": [{"kind": "eq", "args": [
            {"kind": "var", "name": "untyped_a"}, {"kind": "var", "name": "untyped_b"}]}]}
        with self.assertRaisesRegex(ValueError, "unresolved variable"):
            compile_rule(unknown, self.signatures)

    def test_reserved_source_names_and_generated_collisions_reject(self):
        for reserved in ("__lhs_v0", "@_", "$global"):
            rule = deepcopy(self.original)
            rule["body"] = transform(rule["body"], {"e1": {"kind": "var", "name": reserved}})
            with self.subTest(name=reserved), self.assertRaisesRegex(ValueError, "reserved source variable"):
                compile_rule(rule, self.signatures)
        signatures = deepcopy(self.signatures)
        signatures["Collision_cell_0"] = {"kind": "relation", "input": [], "output": "Unit"}
        plan = compile_rule(self.original, signatures)
        with self.assertRaisesRegex(ValueError, "collides"):
            plan.emit("Collision")
        with self.assertRaisesRegex(ValueError, "identifier"):
            self.plan.emit("bad prefix")

    def test_emission_is_deterministic_and_snapshot_names_are_separate(self):
        self.assertEqual(self.plan.emit("First"), self.plan.emit("First"))
        first, second = self.plan.emit("First"), self.plan.emit("Second")
        self.assertNotEqual(first["ruleset"], second["ruleset"])
        self.assertNotEqual(first["declarations"], second["declarations"])
        self.assertEqual(set(first), {"declarations", "producer_rules", "ruleset", "rewritten_body"})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ast", type=Path, default=AST_PATH,
                        help="JSON produced by examples/lhs_ast.rs from the schema plus actual CICM source")
    args, remaining = parser.parse_known_args()
    AST_PATH = args.ast
    unittest.main(argv=[__file__, *remaining])
